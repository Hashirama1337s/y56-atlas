# Task A: second-tool count of automorphisms of the 56-line intersection graph (igraph/bliss), group closure of
# bliss generators, comparison with the networkx VF2 enumeration, and exact realisability of every element.
import sys, pickle, itertools, time
sys.path.insert(0, '../../core/code/sisters')
from q2 import *
import igraph as ig, networkx as nx
t0 = time.time()
d = pickle.load(open('../../core/code/sisters/s1_group.pkl', 'rb')); E = d['E']; n = 56
L = load_lines(); S = load_syms()
# (0) recompute the edge set exactly from the lines (independent of the pickle) and compare
def meets(i, j): return det([L[i][0], L[i][1], L[j][0], L[j][1]]).iszero()
E2 = [(i, j) for i, j in itertools.combinations(range(n), 2) if meets(i, j)]
print('edge set recomputed exactly from lines == s1 pickle:', sorted(E2) == sorted(E), len(E2))
g = ig.Graph(n=n, edges=E2)
cnt = g.count_automorphisms(sh='fl')
gens = g.automorphism_group(sh='fl')
print('igraph/bliss count_automorphisms:', cnt, ' generators returned:', len(gens))
# close the group generated by bliss generators
comp = lambda p, q: tuple(p[q[i]] for i in range(n))
idp = tuple(range(n)); grp = {idp}; frontier = [idp]
gens = [tuple(x) for x in gens]
while frontier:
    nf = []
    for h in frontier:
        for s in gens:
            k = comp(s, h)
            if k not in grp: grp.add(k); nf.append(k)
    frontier = nf
print('closure of bliss generators: order', len(grp))
# all are graph automorphisms (direct check)
Es = set(map(frozenset, E2))
print('every closure element preserves the edge set:', all({frozenset((p[a], p[b])) for a, b in E2} == Es for p in grp))
GM = nx.algorithms.isomorphism.GraphMatcher(nx.Graph(E2), nx.Graph(E2))
vf2 = {tuple(m[i] for i in range(n)) for m in GM.isomorphisms_iter()}
print('networkx VF2 set size', len(vf2), ' equal to bliss closure as sets:', vf2 == grp)
# exact realisability (same linear system as s1, but run on the bliss-derived list)
NRM = [nullspace([l[0], l[1]], 4) for l in L]
def dimsol(perm):
    rows = [[nv[a]*p[b] for a in range(4) for b in range(4)] for i in range(n) for nv in NRM[perm[i]] for p in L[i]]
    return len(nullspace(rows, 16))
dims = {p: dimsol(p) for p in grp}
from collections import Counter
print('solution-space dimensions over the 64:', Counter(dims.values()))
listed = {tuple(sig) for _, _, _, sig in S}
real = {p for p, k in dims.items() if k == 1}
print('realised (dim 1) == listed 32:', real == listed, len(real))
# is the realised set a subgroup of index 2? what does an unrealised automorphism look like?
print('realised closed under composition:', all(comp(a, b) in real for a in real for b in real))
un = sorted(grp - real)
u = un[0]
cyc = []; seen = set()
for i in range(n):
    if i in seen: continue
    c = [i]; seen.add(i); j = u[i]
    while j != i: c.append(j); seen.add(j); j = u[j]
    cyc.append(len(c))
print('cycle type of an unrealised automorphism:', Counter(cyc))
ords = Counter()
for p in un:
    k, q = 1, p
    while q != idp: q = comp(p, q); k += 1
    ords[k] += 1
print('orders of the 32 unrealised automorphisms:', dict(ords))
pickle.dump(dict(grp=sorted(grp), real=sorted(real)), open('a_aut.pkl', 'wb'))
print('time %.1fs' % (time.time() - t0))

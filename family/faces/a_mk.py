# Task A setup: write the 56-line intersection graph and the 32 listed line permutations as a GAP input (a_aut.g).
import pickle, sys
sys.path.insert(0, '../../core/code/sisters')
from q2 import load_syms
d = pickle.load(open('../../core/code/sisters/s1_group.pkl', 'rb'))
E = d['E']; S = load_syms()
NL = chr(92) + 'n'
with open('a_aut.g', 'w') as f:
    f.write('edgs:=Set([' + ','.join('[%d,%d]' % (i+1, j+1) for i, j in E) + ']);;\n')
    f.write('gens:=[' + ','.join('PermList([' + ','.join(str(x+1) for x in sig) + '])' for _, _, _, sig in S) + '];;\n')
    f.write('aut:=Stabilizer(SymmetricGroup(56),edgs,OnSetsSets);;\n')
    f.write('Print("order Aut(graph), GAP partition backtrack: ",Size(aut),"%s");\n' % NL)
    f.write('hh:=Group(gens);;\n')
    f.write('Print("group generated by 32 listed perms: order ",Size(hh)," subgroup ",IsSubgroup(aut,hh)," index ",Index(aut,hh)," normal ",IsNormal(aut,hh),"%s");\n' % NL)
    f.write('Print("IdGroup(aut) ",IdGroup(aut)," IdGroup(listed) ",IdGroup(hh),"%s");\n' % NL)
    f.write('Print("listed set = group: ",Size(Set(gens))=Size(hh),"%s");\n' % NL)
    f.write('PrintTo("a_aut_elems.txt",List(Elements(aut),g->ListPerm(g,56)));\n')
    f.write('QUIT;\n')
print('edges', len(E))

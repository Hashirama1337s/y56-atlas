# Referee part 2: signature, h, complement v, index, primitivity, orbit membership, 16-line identification.
import sympy as sp, json, itertools, numpy as np, mpmath as mp
from sympy import Matrix
from sympy.matrices.normalforms import smith_normal_form, hermite_normal_form
D0='../../core/data/'
inc=set(tuple(sorted(e)) for e in json.load(open(D0+'edges.json')))  # verified equal to exact recomputed incidence in ref_y56.py
G=lambda i,j: -2 if i==j else (1 if (min(i,j),max(i,j)) in inc else 0)
SP=[0,6,10,11,12,19,29,33,35,36,42,44,48,50,54,55]; P40=[i for i in range(56) if i not in SP]
M56=np.array([[G(i,j) for j in range(56)] for i in range(56)])
ev=np.linalg.eigvalsh(M56[np.ix_(P40,P40)]); print('40 Gram eig: pos',sum(ev>1e-8),'neg',sum(ev<-1e-8),'zero',sum(abs(ev)<=1e-8))
# Z-basis of the 56-line lattice: greedy pick of 20 lines with full rank, then check they generate (Smith of inclusion)
def zbasis(idx):
    # returns integer matrix whose rows express a Z-basis of span(idx) in terms of the 56 generators
    # L = Z^56/ker(M56); generators e_i, i in idx. Coordinates: image under M56 (injective on L): rows M56[i]
    R=Matrix([list(M56[i]) for i in idx])
    H=hermite_normal_form(R.T).T   # rows: Z-basis of row lattice generated by R rows
    H=Matrix([list(H.row(k)) for k in range(H.rows) if any(H.row(k))])
    return H
B56=zbasis(list(range(56))); B40=zbasis(P40)
print('Z-basis sizes',B56.rows,B40.rows)
# Gram on image coords: x = M56 y -> pairing y1^T M56 y2 ; recover y via pseudo-solve: use rational solve on M56 restricted
Mq=Matrix(M56.tolist())
def gram_of(B):
    Ys=[]
    for k in range(B.rows):
        y=Mq.gauss_jordan_solve(B.row(k).T)[0]; y=y.subs({s:0 for s in y.free_symbols}); Ys.append(y)
    Y=Matrix.hstack(*Ys); return Y.T*Mq*Y, Y
Q56,Y56=gram_of(B56); Q40,Y40=gram_of(B40)
print('det Q56',Q56.det(),' det Q40',Q40.det())
# index of 40-lattice in its saturation inside 56-lattice: express B40 rows in B56 basis
C=Matrix([list(B56.T.gauss_jordan_solve(B40.row(k).T)[0]) for k in range(B40.rows)])
print('inclusion 40->56 Smith diag',[smith_normal_form(C,domain=sp.ZZ)[k,k] for k in range(19)])
# h class: plane sections with 4 lines -> sum is h. Take planes from planes_exact
import re
txt=open(D0+'planes_exact.txt').read()
P4=[[int(t) for t in m.group(1).split(',')] for m in re.finditer(r'lines \[([0-9, ]+)\]',txt)]
P4=[p for p in P4 if len(p)==4]
h=Matrix([sum(M56[i,k] for i in P4[0]) for k in range(56)])
print('h.L all 1:',all(x==1 for x in h),'  4-line planes:',len(P4),' planes inside the 40:',sum(all(i in P40 for i in p) for p in P4))
# v: generator of orthogonal complement of 40-lattice in 56-lattice
O=Q56.copy(); Bcoords=C  # rows of 40-basis in 56-basis
N=(Bcoords*Q56).nullspace(); assert len(N)==1
v=N[0]*sp.ilcm(*[sp.fraction(t)[1] for t in N[0]]); v=v/sp.igcd(*[int(t) for t in v])
vv=(v.T*Q56*v)[0]
# pairings with lines: line k in 56-basis coords
Lk=[B56.T.gauss_jordan_solve(Matrix(M56[k]).reshape(56,1))[0] for k in range(56)]
pv=[int((Lk[k].T*Q56*v)[0]) for k in range(56)]
print('v.v',vv,' v.L nonzero',{k:pv[k] for k in range(56) if pv[k]},)
print('v.h', sum(pv[i] for i in P4[0]))
# index of (N40 + Zv) in N56
Mix=Matrix.vstack(C, v.T); print('index [N56 : N40+Zv] =',abs(Mix.det()))
plus=[k for k in range(56) if pv[k]>0]; minus=[k for k in range(56) if pv[k]<0]
print('plus',plus,'minus',minus, ' union == listed 16:',sorted(plus+minus)==SP)
# 2v relation: sum(minus)-sum(plus)
lhs=sum((Lk[k] for k in minus),Matrix.zeros(20,1))-sum((Lk[k] for k in plus),Matrix.zeros(20,1))
print('sum(minus)-sum(plus) == 2v:',lhs==2*v,' == -2v:',lhs==-2*v)
# orbit of L00 under the 32 symmetries
sig=[eval(l.split('sigma=')[1]) for l in open(D0+'symmetry_exact.txt') if 'sigma=' in l]
orb={0}; ch=True
while ch:
    ch=False
    for sgm in sig:
        for x in list(orb):
            if sgm[x] not in orb: orb.add(sgm[x]); ch=True
print('n symmetries',len(sig),' orbit of L00',sorted(orb),' == listed 16:',sorted(orb)==SP)
json.dump({'plus':plus,'minus':minus},open('ref_pm.json','w'))

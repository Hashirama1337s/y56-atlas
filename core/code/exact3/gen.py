# Generates fano.sing (exact Fano scheme count for Y56).
import random, sympy as sp
r2 = sp.sqrt(2)
rows=[]
for ln in open('../../data/lines_exact.txt'):
    if not ln.startswith('L'): continue
    a,b = ln.split(':',1)[1].split('|')
    rows.append([[sp.sympify(x) for x in eval(h)] for h in (a,b)])
assert len(rows)==56
def cl(e): return sp.expand(sp.radsimp(sp.expand(e)))
def nf(e):
    e = cl(e); q = e.coeff(r2); p = sp.expand(e-q*r2)
    assert p.is_Rational and q.is_Rational, e
    return (p,q)
def sing(e):
    p,q = nf(e); return f"(({p})+({q})*s)"
random.seed(7)
while True:
    T = sp.Matrix(4,4,lambda i,j: random.randint(-3,3))
    if T.det()==0: continue
    Ti = T.inv(); ok=True; params=[]
    for L in rows:
        N = (Ti*sp.Matrix(L).T).T.applyfunc(cl)
        if nf(N[0,0]*N[1,1]-N[0,1]*N[1,0])==(0,0): ok=False;break
        Bi = N[:,0:2].inv().applyfunc(cl)
        R = (Bi*N).applyfunc(cl)
        assert nf(R[0,0]-1)==(0,0) and nf(R[1,1]-1)==(0,0) and nf(R[0,1])==(0,0) and nf(R[1,0])==(0,0)
        params.append([R[0,2],R[0,3],R[1,2],R[1,3]])
    if ok: break
keys=[tuple(nf(x) for x in P) for P in params]
assert len(set(keys))==56, "lines not distinct in chart"
print("T =",T.tolist(),"; 56 distinct chart points")
Tl=T.tolist()
Fz=lambda z:f"3*s*{z[0]}^2*{z[1]}*{z[2]}+3*s*{z[1]}*{z[2]}*{z[3]}^2-s*{z[1]}^3*{z[2]}-s*{z[1]}*{z[2]}^3+4*{z[0]}^3*{z[3]}-4*{z[0]}*{z[3]}^3"
S=["// Generated by gen.py. Fano scheme of lines of Y56 after rational change of coords z=T w, T="+str(Tl),
   "ring R=(0,s),(a,b,c,d,m),dp; minpoly=s^2-2;"]
body=['proc chart(int i,int j)','{',
 ' int k; int l; int t; list ot; for(t=0;t<=3;t++){ if(t!=i && t!=j){ ot=ot+list(t);} }',
 ' k=ot[1]; l=ot[2]; list p=0,0,0,0; list q=0,0,0,0;',
 ' p[i+1]=1; p[k+1]=a; p[l+1]=b; q[j+1]=1; q[k+1]=c; q[l+1]=d;',
 ' list w; for(t=1;t<=4;t++){ w[t]=m*p[t]+q[t]; }']
for r in range(4):
    body.append(f" poly z{r}="+"+".join(f"({Tl[r][c]})*w[{c+1}]" for c in range(4))+";")
body += [" poly G="+Fz(['z0','z1','z2','z3'])+";",
 " matrix C=coeffs(G,m); ideal I=C[1,1],C[2,1],C[3,1],C[4,1],C[5,1];",
 " poly p01=p[1]*q[2]-p[2]*q[1];",
 " return(list(I,p01));",'}']
S.append('\n'.join(body))
S.append('''
list rs=chart(0,1); ideal I=rs[1]; ideal G0=std(I+ideal(m));
"CHART {0,1}: dim =",dim(G0),"  vdim (degree with multiplicity) =",vdim(G0);
int i; int j; list r2c; ideal Ic; ideal Gc;
for(i=0;i<=2;i++){ for(j=i+1;j<=3;j++){ if(!(i==0 && j==1)){
  r2c=chart(i,j); Ic=r2c[1],r2c[2]; Gc=std(Ic);
  "chart",i,j,": std(I + (p01)) =",Gc[1],"   (1 = no Fano point with p01=0)";
}}}
int bad=0; map ev; ideal e;''')
for P in params:
    S.append(f"ev=R,{','.join(sing(x) for x in P)},m; e=ev(I); if(size(e)!=0){{bad=bad+1;}}")
S.append('"lines (of 56) failing the 5 equations:",bad;\nquit;')
open('fano.sing','w').write('\n'.join(S))
